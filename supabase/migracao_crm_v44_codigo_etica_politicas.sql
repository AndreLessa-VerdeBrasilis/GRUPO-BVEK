5. ÂMBITO DE APLICAÇÃO E CUMPRIMENTO

Os termos estabelecidos neste Código de Ética e Conduta são mandatórios e se aplicam a todos os sócios e colaboradores da Verde Brasilis, entendendo-se no contexto deste Código de Ética e Conduta, todos os membros de conselhos ou comitês, a Alta Direção, os empregados, os estagiários e os jovens aprendizes. Portanto, todos são responsáveis por respeitar o estabelecido neste Código e manter suas condutas nos mais elevados padrões éticos, além de comunicar qualquer conduta que não siga essas diretrizes.

É previsto ainda a proposição de adoção de nossos valores e princípios às organizações parceiras e fornecedores em todas as atividades conjuntas ou em que a Verde Brasilis seja beneficiada ou possua algum interesse envolvido.


6. RELACIONAMENTOS

Consciente dos impactos de suas atividades em toda a sociedade e no meio ambiente, a Verde Brasilis possui em seu Norte o respeito pelas individualidades e busca a minimização de impacto no meio ambiente.

A Verde Brasilis, neste sentido, possui a Declaração Universal dos Direitos Humanos adotada e proclamada pela Assembleia Geral das Nações Unidas como um dos pilares deste Código de Ética e Conduta.

Em razão disso, considera em todas as suas decisões a isonomia de tratamento entre todos os colaboradores, parceiros, fornecedores, clientes ou qualquer um da sociedade que venha a ser impactado por nossas atividades, sem distinção de qualquer natureza, independentemente, de cor, etnia, opção religiosa, política, gênero, estado civil, nacionalidade, orientação sexual, deficiência, idade, opinião, classe social, dentre tantas outras.

Nosso ambiente é de respeito às competências individuais das pessoas e à diversidade dos membros de nossas equipes.

6.1. RELACIONAMENTO COM CLIENTES

A Verde Brasilis tem o compromisso de fornecer serviços e produtos em condições apropriadas e em estrita conformidade à legislação e ao contratado com cada cliente, atentando sempre para:

a. O estabelecimento de uma relação de confiança e lealdade mútua;
b. A prestação de serviços com a máxima qualidade e segurança;
c. A adoção de uma comunicação baseada em informações claras, verdadeiras e consistentes a respeito de nossas ações, serviços e produtos;
d. O atendimento de compromissos comerciais baseados em preço, prazo, qualidade e condições para cada tipo de serviço/produto;
e. Cordialidade e respeito com os clientes e com o público de nossos clientes.

A Verde Brasilis, previamente à contratação, verificará a conveniência e a oportunidade em manter relações comerciais com a organização, mas, ocorrendo a contratação, declara total respeito às regras, ao Código de Ética e às demais políticas existentes de nossos clientes.

Todos os bens, dados e informações acessados pela Verde Brasilis para execução de um contrato serão utilizados e tratados em total conformidade com o estabelecido pelas regras do cliente.

Eventualmente, os clientes da Verde Brasilis podem vir a fazer parte de sua cadeia de fornecedores, entretanto, jamais as atividades serão praticadas pelo único critério de reciprocidade.

6.2. RELACIONAMENTO COM COLABORADORES

Nosso ambiente é de respeito às competências individuais das pessoas e à diversidade de toda a nossa equipe.

I. Contratação e Promoção

Em qualquer desses processos o candidato deve ser cuidadosamente avaliado quanto às exigências e requisitos técnicos e profissionais relativos ao exercício de cada função, não sendo toleradas quaisquer formas de favorecimentos ou privilégios.

Não deverá existir discriminação ou segregação quanto à participação de pessoas portadoras de necessidades especiais nos processos seletivos. Ao contrário, a Verde Brasilis incentiva a admissão de profissionais com esse perfil em funções compatíveis, de acordo com as determinações legais.

Todos os novos colaboradores, incluindo pessoa jurídica, passarão por um processo de integração e treinamentos, inclusive quanto ao Programa de Compliance da Verde Brasilis, seus valores, princípios e regras que devem ser seguidos.

No preenchimento de vagas, a Verde Brasilis considera o aproveitamento de pessoal interno uma forma de propiciar oportunidade de crescimento profissional.

Os critérios que norteiam a promoção de um colaborador são: mérito, experiência e atitudes individuais indispensáveis ao crescimento profissional.

II. Desempenho, Educação e Treinamento

O colaborador deve atender às normas e regras internas e de clientes da Verde Brasilis, sendo considerada sua atribuição de adquirir conhecimentos, habilidades e atitudes necessárias ao bom desempenho de sua função, inclusive representar a empresa junto a órgãos públicos ou privados, quando solicitado. Cabe à empresa orientá-lo nesse sentido.

A Verde Brasilis segue os critérios de avaliação dos seus colaboradores orientada pelo RAC – Relatório de Avaliação do Colaborador.

É atribuída aos gestores a responsabilidade de avaliação e orientação, individualmente, de informações que favoreçam o crescimento profissional dos colaboradores. Considera-se o elogio um instrumento salutar de orientação, reconhecimento e motivação.

Elogios devem ser feitos em público e advertências, caso necessárias e construtivas, em particular.

O líder deverá dedicar especial atenção à motivação e ao desenvolvimento profissional da equipe, comprometendo-se a propiciar oportunidades de desenvolvimento, tendo como base as competências requeridas pela empresa e sua contribuição profissional. Para isso, deve incentivar a empregabilidade de seus colaboradores, fomentar sua formação e aprendizagem, reconhecer seus esforços de forma específica e valorizar objetivamente seus êxitos.

A Verde Brasilis promoverá todos os treinamentos necessários e exigidos em legislação e proverá seus colaboradores de todos os equipamentos de proteção individual, coletivo e/ou ergonômicos para garantir um ambiente saudável, sem acidentes de trabalho e ambientais.

Em suas atividades diárias, eventuais erros devem ser tratados com compreensão e orientação construtiva. A repetição de erros resultantes de descuido, negligência ou falta de interesse deve merecer atenção especial em sua sinalização, pois pode, em último caso, estar sujeito à aplicação de medidas disciplinares.

Atos irregulares e contrários ao estabelecido neste Código de Ética e Conduta deverão ser reportados ao Canal de Denúncia e sofrerão o devido tratamento.

III. Relacionamento no Trabalho

É compromisso da Verde Brasilis orientar os colaboradores para o relacionamento entre si tendo como referência os seguintes princípios:

a. Os relacionamentos no trabalho devem orientar-se pela confiança, honestidade, integridade, conformidade, imparcialidade e respeito mútuo.
b. A conciliação entre os interesses da empresa e do colaborador deve ocorrer, prioritariamente, por meio do diálogo na relação direta entre os colaboradores e suas lideranças.
c. Intolerância com práticas abusivas contra colaboradores, como assédio moral ou sexual, arrogância, pressões, intimidações ou ameaças.
d. Avaliação periódica de todos os colaboradores com discussão do resultado, com o objetivo de ressaltar pontos fortes e sinalizar pontos que precisam melhorar.
e. A preservação da saúde, da integridade física e do meio ambiente é prioritária em relação aos interesses econômicos.

Todo o tratamento que for considerado inadequado e contrário aos valores, princípios e regras estabelecidos neste Código de Ética e Conduta deverão ser reportados ao Canal de Denúncia e terão o devido tratamento.

IV. Conflito de Interesses

Os colaboradores devem ter lealdade à empresa e comprometimento com os valores, a missão, a visão, os objetivos, os princípios e as normas estabelecidas pela Verde Brasilis.

Todos os atos pela ou para a Verde Brasilis devem estar de acordo com os procedimentos legais e devem ser norteados pela consciência profissional e o mais elevado padrão ético, sem pleitear ou incorrer em vantagens pessoais ao colaborador ou a terceiros.

V. Utilização de Mídias Sociais e a Relação com a Imprensa

A Verde Brasilis é favorável a todas as manifestações individuais e à liberdade de expressão, entretanto, não tolera qualquer ato de injúria, infâmia ou calúnia de qualquer natureza, cometida por seus colaboradores em redes sociais ou em qualquer outra mídia social.

Deve-se ter os seguintes pontos de atenção:
• Não postar fotos do ambiente de trabalho e de ambientes internos de clientes;
• Jamais opinar ou emitir juízo de valor sobre a Verde Brasilis, seus clientes ou concorrentes;
• Não divulgar, publicar ou disseminar informações da Verde Brasilis, ou em sua posse, salvo se forem classificadas como públicas ou manifestamente de domínio público.

A Verde Brasilis possui total consciência da importância das mídias sociais e da Imprensa e se reserva ao direito de se manifestar exclusivamente por seus diretores. Portanto, é vedada qualquer manifestação em mídias sociais ou para a imprensa em seu nome ou com qualquer fardamento, roupa, uniforme ou qualquer objeto que identifique o agente como colaborador da Verde Brasilis, sem a prévia autorização da Direção.

VI. Atividades Paralelas

O colaborador pode realizar atividades paralelas fora de sua jornada de trabalho ou fora do ambiente de trabalho, tendo consciência e cuidado para jamais expor ou denegrir a reputação e a marca Verde Brasilis. Em momento algum será permitido o desenvolvimento de atividade paralela para concorrentes da Verde Brasilis.

Nenhum material, equipamento ou ativo, de propriedade da Verde Brasilis, ou de terceiros em sua posse, deve ser utilizado para a realização de atividade paralela.

Nenhuma informação, dado ou documento de propriedade ou sobre a Verde Brasilis deve ser utilizado em qualquer tipo de evento profissional ou pessoal, salvo com autorização expressa da Direção.

VII. Atividades Religiosas

A Verde Brasilis respeita todas as manifestações religiosas e a liberdade de expressão, entretanto, não se associa a qualquer religião e, nem tampouco, permite manifestações de qualquer natureza em suas dependências ou onde estiver prestando serviços, salvo se existir autorização prévia da Direção.

VIII. Relacionamento Afetivo

Parentes de colaboradores deverão concorrer em igualdade de condições com os demais candidatos, não se admitindo, contudo, a subordinação direta entre cônjuges, avós, pais, filhos, sogros, genros, noras, irmãos e cunhados (por consanguinidade ou afetividade, até o 3º grau).

Não é permitido o relacionamento afetivo entre colaboradores com subordinação ou inseridos dentro de uma mesma linha de reporte superior.

Qualquer relacionamento afetivo existente, inclusive de parentesco, entre colaboradores e colaboradores de clientes deve ser declarado para a Verde Brasilis.

IX. Atividade Político-Partidária

A Verde Brasilis é amplamente favorável à manifestação dos indivíduos, entretanto, não realiza qualquer doação financeira ou qualquer outra ação que se traduza em dinheiro para candidatos ou partidos políticos.

Em razão disso e pela nova legislação vigente, é mandatório que qualquer colaborador que seja candidato ou realize doação eleitoral comunique o fato para a Verde Brasilis.

X. Utilização de Bens

Não é permitida a utilização de qualquer bem da Verde Brasilis, material ou imaterial, próprio ou de terceiros, para qualquer fim que não sejam os compromissos, tarefas e obrigações da própria empresa.

Para fins de mera exemplificação, citamos alguns tipos de bens acima dispostos:
1. Automóvel;
2. Material de escritório;
3. Informações de clientes;
4. Imóvel;
5. Informação de formação de preço;
6. Informação de contratos;
7. Informação em participação em concorrência, pública ou privada;
8. Softwares;
9. Logomarca;
10. Projeto de novo produto;
11. Insumo de limpeza;
12. Plano de negócios;
13. Energia elétrica;
14. Computador e telefone;
15. Banco de dados.

Todos os bens cedidos ou em posse de colaboradores ou terceiros para o desempenho de uma determinada atividade devem ser retornados para a empresa, tão logo cessada sua necessidade.

Qualquer desvio ou má utilização de bens da empresa ou que estejam em sua posse deve ser imediatamente comunicado ao Canal de Denúncia.

XI. Proteção de Dados

A Verde Brasilis tem o compromisso com a privacidade e a proteção dos dados pessoais, inclusive daqueles coletados de seus parceiros de negócio. Assim, a Verde Brasilis exige que todos os seus parceiros de negócio possuam políticas, controles e estejam compromissados com as diretrizes a seguir:

• Adotar medidas de proteção aos dados pessoais, ativos de informação e ambientes, de forma a reduzir os riscos de falhas, danos e/ou prejuízos que possam causar um incidente.
• Promover ações de aculturamento de seus colaboradores sobre os temas de segurança da informação e de proteção de dados pessoais.
• Atender aos requisitos de segurança e transparência, aos padrões de boas práticas e de governança e aos princípios gerais estabelecidos na Lei Geral de Proteção de Dados Pessoais (“LGPD”) e pela Autoridade Nacional de Proteção de Dados.
• Tomar todas as medidas cabíveis para manter o absoluto sigilo e a estrita confidencialidade de todos os dados pessoais e informações relacionadas à pessoa natural, identificada ou identificável, as quais tiver acesso ou que porventura venha a conhecer ou ter ciência, restringindo o tratamento dos dados pessoais a colaboradores e terceiros autorizados, dentro do limite necessário para atendimento das finalidades estabelecidas pela Verde Brasilis.
• Nomear um Encarregado de Proteção de Dados para fazer cumprir as exigências da Lei Geral de Proteção de Dados Pessoais (LGPD).
• Garantir que em quaisquer incidentes ou vulnerabilidades técnicas que possam vir a colocar em risco dados pessoais recebidos da Verde Brasilis, sejam imediatamente comunicados à Verde Brasilis, a fim de possibilitar o cumprimento do prazo para comunicar a Autoridade Nacional de Proteção de Dados.
• Caso o fornecedor seja um provedor de serviços de computação em nuvem ou faça uso de tecnologia de computação em nuvem como parte da prestação dos serviços para a Verde Brasilis, os dados pessoais, dados sensíveis e/ou confidenciais devem ser transmitidos, registrados e/ou armazenados adotando medidas de segurança e governança mínimas exigidas no Brasil.
• Assegurar que a transferência de dados pessoais para outro país seja realizada quando este assegurar um nível adequado de proteção dos direitos e liberdades do Titular de dados pessoais, adoção de cláusulas contratuais específicas e salvaguardas exigidas pelas Leis de Proteção de Dados aplicáveis e mediante prévia autorização da Verde Brasilis.
• Assegurar que a segurança da informação e a proteção de dados seja implantada e operada em conformidade com as políticas, normas e procedimentos da organização, de maneira a evitar quaisquer violações de obrigações legais ou contratuais relacionadas à segurança da informação, proteção de dados e de quaisquer requisitos de segurança que afetem a Verde Brasilis e os titulares de dados pessoais.

6.3. RELACIONAMENTO COM O PODER PÚBLICO

A Verde Brasilis possui amplo espectro de relacionamento com o Poder Público, através de licitações, fiscalizações, regulações, certidões entre tantas.

Em razão do amplo relacionamento com o Poder Público é de suma importância o regramento dessa interação. Neste sentido, seus colaboradores e todos os terceiros que realizam atividades para ou em nome dela possuem a obrigação de manter relações com o Poder Público dentro dos mais estritos padrões de moralidade, cordialidade e ética.

Poder Público para fins deste Código de Ética e Conduta é toda a organização e entidade pública que realiza função legislativa, judiciária ou executiva, bem como nos casos e em casos específicos, em que o Poder Público realiza uma função empresarial propriamente dita.

É terminantemente vedado aos colaboradores e todos os terceiros que realizam atividades para ou em nome da Verde Brasilis, prometer, oferecer ou dar, direta ou indiretamente através de terceiros, vantagem indevida a agentes públicos ou a terceiro por ele indicado. A vantagem indevida para fins deste Código deve ser interpretada como qualquer benefício, financeiro ou não, para que seja praticado, retardado ou omitido ato de ofício.

Dessa forma, é mandatório o estrito cumprimento das normas relativas à corrupção e crimes contra a Administração Pública, vigentes ou que venham ser promulgadas, brasileira e estrangeira, principalmente na Lei Anticorrupção (Lei nº 12.846/2013), no Código Penal (Decreto-Lei nº 2.848/1940) e Lei de Licitações (Lei nº 8.666/93), o FCPA (Foreign Corrupt Practices Act), o UK Bribery Act, mas não somente.

Demais informações e regras específicas devem ser consultadas na Política e procedimentos correspondentes.

6.4. RELACIONAMENTO COM TERCEIROS

CONCORRENTES

A Verde Brasilis procura ter um relacionamento respeitoso e leal com seus concorrentes e desta forma se faz valer por seus próprios méritos e vantagens, em total consonância com a livre concorrência e as leis de mercado.

Não são admitidas atitudes que representem concorrência desleal e práticas comerciais antiéticas, estabelecido pela defesa da concorrência – Lei nº 12.529/2011. Exigimos de nossos colaboradores a não depreciação dos concorrentes, seus produtos ou serviços e jamais conversar ou trocar informações sobre dados concorrencialmente sensíveis com concorrentes, como por exemplo: preços, formação de preços, propostas, participação em concorrências, estratégias de mercado etc.

Demais informações e regras específicas devem ser consultadas na Política e procedimentos correspondentes.

