9. BRINDES, PRESENTES E HOSPITALIDADES CORPORATIVAS

A Verde Brasilis tem consciência da regular prática comercial de oferecimento de brindes, presentes e hospitalidades corporativas, cujo objetivo é o legítimo estreitamento dos laços comerciais.

Para fins deste Código de Ética e Conduta define-se o presente como um objeto ou serviço que possui valor comercial (bebidas, ingressos, aparelhos eletrônicos etc.), enquanto o brinde é um objeto sem valor comercial, distribuído de forma generalizada por organizações de qualquer natureza a título de cortesia, propaganda, divulgação habitual ou por ocasião de eventos especiais ou datas comemorativas (agendas, canetas, calendários, canecas etc.). Por fim, hospitalidade são despesas com deslocamento, hospedagem, alimentação e receptivo relacionadas a algum evento (por exemplo: convite para participação em eventos promovidos, apoiados ou patrocinados por empresa, convite para apresentação de produtos e serviços ou das dependências de empresa etc.). A Verde Brasilis jamais ofertará ou aceitará o oferecimento de brindes, presentes ou hospitalidades corporativas sem um propósito comercial legítimo e que estejam atrelados a alguma contraprestação ou alguma retribuição.

No relacionamento com o Poder Público não poderá ser oferecido qualquer presente ou hospitalidade a um agente público, salvo brindes que não ultrapassem R$ 100,00.

Nas relações comerciais com as organizações privadas, o oferecimento e o recebimento de brindes, presentes e hospitalidades jamais poderão estar atrelados a qualquer tipo de contrapartida ou retribuição, bem como deverão atender às regras de ambas as organizações.

Por fim, ressalta-se que a Verde Brasilis se coloca totalmente contrária a receber ou oferecer qualquer benefício, pecuniário ou não, em troca de favores ou privilégios e que envolvam práticas de corrupção ou pagamento de propina.

Demais informações e regras específicas devem ser consultadas na Política e procedimentos correspondentes.


10. SEGURANÇA DA INFORMAÇÃO

A Verde Brasilis possui o compromisso de manter a confidencialidade, a integridade e a disponibilidade das informações e sistemas da empresa, possuindo diretrizes com as melhores práticas de comportamento relacionados à segurança da informação e adequados às necessidades do negócio e de proteção da informação.

É compromisso da Verde Brasilis preservar as informações quanto à:
1. Integridade: garantia de que a informação seja mantida em seu estado original, visando protegê-la, na guarda ou transmissão, contra alterações indevidas, intencionais ou acidentais.
2. Confidencialidade: garantia de que o acesso à informação seja permitido somente a pessoas autorizadas.
3. Disponibilidade: garantia de que os usuários autorizados obtenham acesso à informação.
4. A divulgação de dados e informações internas da Verde Brasilis ou de terceiros que a Verde Brasilis teve acesso ou tem posse por força contratual, para o meio externo, só poderá ser realizada com autorização prévia e por escrito da Direção.
5. O colaborador é terminantemente proibido de utilizar, em benefício próprio ou de terceiros, as informações da empresa ou de terceiros que a Verde Brasilis teve acesso ou tem posse por força contratual, mesmo depois de seu desligamento.
6. Segurança: a garantia da proteção de dados em conformidade com a Lei Geral de Proteção de Dados e das políticas, normas e procedimentos da organização, de maneira a evitar quaisquer violações de obrigações legais ou contratuais relacionadas à segurança da informação e proteção de dados.
7. É vetado o compartilhamento de informações e dados pessoais, devendo todo colaborador assinar o termo de confidencialidade no ato da admissão ou sempre que houver alteração neste documento.

Demais informações e regras específicas devem ser consultadas na Política e procedimentos correspondentes à Segurança da Informação.


