MENSAGEM DA ALTA DIREÇÃO

O Código de Ética e Conduta é o principal documento norteador da atuação de uma empresa, com base nos princípios de ética, honestidade, respeito e integridade que assume com seus públicos de relacionamento.

Este Código foi elaborado em conformidade com a legislação aplicável aos negócios da Verde Brasilis visando nos orientar a sempre proceder de acordo com os nossos valores: compromisso, ética, inovação, profissionalismo e responsabilidade.

Nossa empresa cultiva relações éticas, verdadeiras e transparentes com governos, sociedade, clientes, administradores, colaboradores, estagiários, jovens aprendizes, prestadores de serviços, parceiros, fornecedores, sindicatos, associações de classe e todos os outros públicos de interesse, pois entendemos que a saúde dessas convivências muito contribui para a realização da nossa missão, a concretização da nossa visão e a construção da nossa marca e imagem institucional.

É essencial que cada colaborador o leia atentamente, de forma a poder usá-lo diariamente como guia de suas ações e decisões, conhecê-lo e fazê-lo conhecido, observando e defendendo seu cumprimento.

Destinamos também o conteúdo a seguir a todos aqueles que tenham algum tipo de relação profissional ou comercial com a Verde Brasilis, por considerarmos que juntos somos todos responsáveis por disseminar a ética e o profissionalismo pelos quais tanto prezamos.

Temos a certeza de que ele é uma ferramenta de trabalho útil e indispensável, capaz de nos inspirar na condução de nossa empresa e na arte de transformar nosso comportamento pessoal e profissional em exemplo para todos.

Direção Verde Brasilis


1. OBJETIVO

O objetivo da elaboração deste Código de Ética e Conduta representa o interesse em promover nossos valores: compromisso, ética, inovação, profissionalismo e responsabilidade. Valores estes que norteiam nossa conduta e servem como fundamentos para estabelecer os princípios e regras da empresa frente aos seus relacionamentos internos e externos, envolvendo colaboradores, clientes, fornecedores, parceiros, comunidade, sociedade, concorrência e Poder Público.

Representa, também, um instrumento de valorização do que temos de mais importante: nosso capital humano, pois cremos que uma equipe bem capacitada, motivada e imbuída desses valores e princípios é capaz de proporcionar o serviço cada vez melhor.

Para nós, está claro que o sucesso dessas ações vai além do cumprimento de normas, mas, também com os valores e princípios traçados neste documento. Em razão disso, a Verde Brasilis está integralmente comprometida na busca da melhoria contínua de nossas atividades.


2. MISSÃO, VISÃO E VALORES

MISSÃO
Ser a melhor e a mais bem preparada empresa de Serviços, atendendo e superando expectativas.

VISÃO
Satisfazer as necessidades dos nossos clientes, maximizando valor para clientes e empresas.

VALORES
Nosso relacionamento com clientes e colaboradores deve ser transparente e baseado na responsabilidade e confiança entre as partes.

• Valorização e respeito às pessoas: São as pessoas o grande diferencial que torna tudo possível.
• Respeito ao Meio Ambiente: É isso que nos dá a perspectiva do amanhã.
• Satisfação do cliente: Ele é a razão da existência de qualquer negócio.
• Foco em Resultados: Com integridade e respeito.

Compromisso
Baseado na dedicação, comprometimento e envolvimento de todos no sentido de alcançar os objetivos organizacionais e manter a qualidade dos serviços prestados.

Ética
É o comportamento que norteia a empresa criando um ambiente de respeito e harmonia, não só entre os colaboradores como também entre a empresa e os clientes, os fornecedores e a sociedade, assegurando assim sua reputação, seus bons resultados e promovendo um contexto comercial sustentável e competitivo.

Inovação
É a busca por soluções com ousadia e determinação, permitindo ganhos de eficiência em processos produtivos, administrativos, financeiros e na prestação de serviços objetivando, para os desafios do dia a dia, o aperfeiçoamento contínuo com sensibilidade e conhecimento.

Profissionalismo
Significa adotar uma postura profissional, especialista e competente em todas as suas ações. Para isso, torna-se necessária a capacitação, formação e crescimento profissional e pessoal.

Responsabilidade
Assumir sempre as ações, reconhecendo erros, valorizando acertos e incentivando a participação de todos para resolução dos problemas, numa busca contínua de melhoria, refletindo caráter e ética em suas relações com os clientes internos, externos e parceiros do nosso negócio.


3. POLÍTICA DO SISTEMA DE GESTÃO INTEGRADO
Qualidade, Meio Ambiente, Saúde e Segurança.

A Verde Brasilis Gestão e Serviços LTDA., atuando na prestação de serviços de manutenção, operação, conservação e limpeza predial, higienização e desinfecção, conservação de áreas verdes, gerenciamento e serviços de engenharia e no fornecimento de mão de obra especializada para apoio técnico e administrativo, nos diversos segmentos das indústrias e serviços, considera como compromissos do seu Sistema de Gestão Integrado:

1. Atender aos requisitos legais aplicáveis e outros requisitos regulamentares subscritos pela organização, por seus clientes e parceiros;
2. Manter seus clientes satisfeitos e fiéis, buscando conhecer suas necessidades, atender suas exigências e procurando superar suas expectativas através dos serviços oferecidos;
3. Manter seus colaboradores treinados, capazes e satisfeitos, consultando-os e participando-os por meio de seus representantes;
4. Melhorar continuamente o desempenho do seu SGI, através do alcance dos objetivos e metas;
5. Proporcionar condições de trabalho seguras e saudáveis, buscando eliminar perigos e reduzir os riscos para segurança e saúde de seus colaboradores, bem como prevenir problemas de saúde e lesões relacionados ao trabalho;
6. Prevenir a poluição e os impactos ao meio ambiente.

