FORNECEDORES

A Verde Brasilis procura tratar todos os seus fornecedores respeitosamente, mas considera parceiras as instituições comprometidas com seus valores e princípios e que divulgam e valorizam sua marca. Com eles a Verde Brasilis procura manter relacionamentos diferenciados e duradouros, baseados na ética, no respeito, na confiança e na lealdade.

A Verde Brasilis reprova em seu cadastro de fornecedores organizações que utilizem mão de obra infantil, escrava, ou análoga, ou cujos produtos ou serviços sejam de origem duvidosa e sejam condenadas em crimes ambientais.

A contratação de fornecedores de serviços e produtos deverá atender rígidos critérios, objetivos técnicos e comerciais. Esse processo, cujo objetivo é a identificação e mitigação de riscos na contratação de terceiros, deve ser conduzido em momento prévio à contratação e exigirá uma diligência para análise da integridade e poderá indicar a necessidade de uma Due Diligence de Integridade com maior aprofundamento. Ao final da Due Diligence de Integridade, a contraparte deverá emitir declaração de sua integridade e ciência e compromisso com os valores e princípios estabelecidos neste Código de Ética e Conduta.

A Verde Brasilis também reprova qualquer tipo de favorecimento ou benefício que tenham como interesse a contratação, incluindo gratificação monetária, presentes e hospitalidades, que não estejam previstos no instrumento contratual e que tenham a finalidade de obter uma retribuição ou uma contrapartida.

Demais informações e regras específicas devem ser consultadas na Política e procedimentos correspondentes.


